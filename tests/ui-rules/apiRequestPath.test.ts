// tests/ui-rules/apiRequestPath.test.ts — every client request to the server goes through
// lib/query-client.ts's api(), which takes its URL and types from shared/http.ts (#1715).
// Each list below is exact: a new request, base-URL read or fetch anywhere fails until it is
// named here, so a reviewer sees it. It reads the syntax tree, not the text, so spacing,
// line breaks and comments cannot hide a reference.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import ts from "typescript";
import { trackedFiles } from "../helpers/trackedFiles.ts";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const owner = "lib/query-client.ts";
const scanned = ["app", "components", "context", "lib", "locales", "modules"];
const notClient: Record<string, string> = {
  server: "runs on the server",
  shared: "the contract itself",
  tests: "never bundled",
  scripts: "build and CI scripts",
  tools: "build and CI scripts",
  "drizzle.config.ts": "the schema tool's config",
  node_modules: "installed packages",
  dist: "build output",
  sourcemaps: "build output",
  ".expo": "generated by Expo",
  ".git": "git's own store",
};
const guarded = new Set(["fetch", "getApiUrl", "requestOf"]);
const isSource = (f: string) => /\.tsx?$/.test(f);

function sourceFiles(dir: string): string[] {
  return readdirSync(path.join(repoRoot, dir), { recursive: true, encoding: "utf8" })
    .filter(isSource)
    .map((f) => path.posix.join(dir, f.split(path.sep).join("/")));
}

function clientTrees(): ts.SourceFile[] {
  return scanned
    .flatMap(sourceFiles)
    .filter((file) => file !== owner)
    .map((file) =>
      ts.createSourceFile(
        file,
        readFileSync(path.join(repoRoot, file), "utf8"),
        ts.ScriptTarget.Latest,
        true,
        file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS
      )
    );
}

function walk(sf: ts.SourceFile, visit: (node: ts.Node) => void): void {
  const go = (node: ts.Node) => {
    visit(node);
    ts.forEachChild(node, go);
  };
  go(sf);
}

/** The call `id` is the callee of, directly or as `x.id(...)`; undefined when it is anything else. */
function callOf(id: ts.Identifier): ts.CallExpression | undefined {
  const callee = ts.isPropertyAccessExpression(id.parent) && id.parent.name === id ? id.parent : id;
  const call = callee.parent;
  return ts.isCallExpression(call) && call.expression === callee ? call : undefined;
}

type Findings = { calls: string[]; strays: string[]; clients: string[]; apiStrings: string[] };

function scan(): Findings {
  const found: Findings = { calls: [], strays: [], clients: [], apiStrings: [] };
  for (const sf of clientTrees()) {
    const at = (node: ts.Node) => `${sf.fileName}:${sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1}`;
    walk(sf, (node) => {
      if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier) && node.moduleSpecifier.text === "expo/fetch") {
        found.clients.push(at(node));
      } else if (ts.isIdentifier(node) && node.text === "XMLHttpRequest") {
        found.clients.push(at(node));
      } else if (ts.isIdentifier(node) && guarded.has(node.text)) {
        if (ts.isImportSpecifier(node.parent) && node.parent.name === node && !node.parent.propertyName) return;
        const call = callOf(node);
        if (call) found.calls.push(`${sf.fileName}: ${call.expression.getText(sf)}(${call.arguments[0]?.getText(sf) ?? ""})`);
        else found.strays.push(at(node));
      } else if (ts.isStringLiteralLike(node) || ts.isTemplateLiteralToken(node)) {
        if (guarded.has(node.text)) found.strays.push(at(node));
        if (/(^|\/)api(\/|$)/.test(node.text)) found.apiStrings.push(at(node));
      }
    });
  }
  return found;
}

test("only api()'s module spells an api/ path; everyone else names a contract route", () => {
  assert.deepEqual(scan().apiStrings, []);
});

test("only api()'s module imports expo/fetch or reaches for XMLHttpRequest", () => {
  assert.deepEqual(scan().clients, []);
});

test("fetch, getApiUrl and requestOf appear only as calls, each one named here", () => {
  const { calls, strays } = scan();
  assert.deepEqual(strays, []);
  assert.deepEqual(calls.sort(), [
    "app/(online)/room.tsx: getApiUrl()",
    'context/AuthContext.tsx: fetch(...requestOf("GET auth/me"))',
    'context/AuthContext.tsx: requestOf("GET auth/me")',
    "lib/device/audioEngine.web.ts: fetch(file as unknown as string)",
    "lib/diagnostics/recorder.ts: fetch(target)",
    "lib/socket.ts: getApiUrl()",
    'lib/socket.ts: fetch(...requestOf("POST auth/socket-ticket"))',
    'lib/socket.ts: requestOf("POST auth/socket-ticket")',
  ].sort());
});

test("every top-level directory with TypeScript in it is scanned or named as not client code", () => {
  const unaccounted = trackedFiles(repoRoot)
    .filter(isSource)
    .map((f) => f.split("/")[0])
    .filter((top) => !scanned.includes(top) && !(top in notClient));
  assert.deepEqual([...new Set(unaccounted)], []);
});
